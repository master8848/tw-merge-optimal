/// Overlay machinery emission: `NF` (compiled family count), the module
/// overlay constants `XO`/`XKW`/`XC`/`OW`, the `m2` matcher, the runtime
/// extend API (`--extend` only) and the `makeBundle` closure factory.
fn overlay_machinery_js(
    table: &ConflictTable,
    patterns: Option<&PatternTable>,
    pat_mode: bool,
    opts: &GenerateOptions,
) -> String {
    let mut js = String::new();

    // NF: first overlay family id; every compiled family id is below it.
    let n_compiled = if pat_mode {
        patterns.unwrap().family_names.len()
    } else {
        table.family_names.len()
    };
    js.push_str(&format!("const NF={n_compiled};\n"));

    // Build-time overlay (exact mode only; patterns mode compiles every
    // config family). A group holding ANY wildcard item becomes one overlay
    // family (ids NF, NF+1, ... by classGroups order) with a flat XO record
    // per item — its statics included; the compiled entries added by
    // apply_plugin_config stay, the G lookup hits first. Statics-only
    // groups stay compiled-only.
    let mut overlay_records: Vec<Record> = Vec::new();
    let mut xkw: Vec<String> = Vec::new();
    let mut theme_sets: Vec<Vec<String>> = Vec::new();
    let mut theme_ids: HashMap<String, usize> = HashMap::new();
    let mut group_to_index: HashMap<&str, usize> = HashMap::new();
    let mut xc: Vec<Vec<u16>> = Vec::new();
    let mut ow: BTreeMap<u16, Vec<u16>> = BTreeMap::new();
    if let Some(cfg) = opts.plugin {
        if !pat_mode {
            let mut fid = n_compiled as u16;
            for (group, items) in &cfg.class_groups {
                if !items.iter().any(|i| matches!(i, GroupItem::Wildcard(_))) {
                    continue;
                }
                group_to_index.insert(group.as_str(), xc.len());
                xc.push(vec![fid]);
                for item in items {
                    match item {
                        GroupItem::Static(cls) => overlay_records.push(Record {
                            name: cls.clone(),
                            elems: vec![
                                js_string(cls),
                                "0".to_string(),
                                fid.to_string(),
                                "0".to_string(),
                                "0".to_string(),
                            ],
                        }),
                        GroupItem::Wildcard(w) => {
                            let mut elems = vec![
                                js_string(&format!("{}-", w.prefix)),
                                "1".to_string(),
                                fid.to_string(),
                                "0".to_string(),
                                "1".to_string(),
                                w.specs.len().to_string(),
                            ];
                            for spec in &w.specs {
                                elems.push(
                                    overlay_spec_code(spec, &mut xkw, &mut theme_sets, &mut theme_ids, opts.ds)
                                        .to_string(),
                                );
                            }
                            overlay_records.push(Record {
                                name: format!("{}-", w.prefix),
                                elems,
                            });
                        }
                    }
                }
                fid += 1;
            }
            // Overlay edges: compiled -> overlay (OW), overlay -> compiled
            // and overlay -> overlay (XC). Compiled -> compiled edges were
            // already patched into the table by apply_plugin_config.
            for (group, targets) in &cfg.conflicting_class_groups {
                let src_compiled = table.family_exists(group).then(|| table.family_id_of(group));
                let src_overlay = group_to_index.get(group.as_str()).copied();
                for t in targets {
                    let t_compiled = table.family_exists(t).then(|| table.family_id_of(t));
                    let t_overlay = group_to_index.get(t.as_str()).copied();
                    if let Some(s) = src_compiled {
                        if let Some(to) = t_overlay {
                            let id = n_compiled as u16 + to as u16;
                            let e = ow.entry(s).or_default();
                            if !e.contains(&id) {
                                e.push(id);
                            }
                        }
                    }
                    if let Some(so) = src_overlay {
                        if let Some(tc) = t_compiled {
                            let e = &mut xc[so];
                            if !e.contains(&tc) {
                                e.push(tc);
                            }
                        }
                        if let Some(to) = t_overlay {
                            let id = n_compiled as u16 + to as u16;
                            let e = &mut xc[so];
                            if !e.contains(&id) {
                                e.push(id);
                            }
                        }
                    }
                }
            }
        }
    }

    // Theme sets (exact mode only — patterns mode emits TH/th with the
    // pattern tables). Only when a build-time overlay record needs one.
    if !theme_sets.is_empty() {
        js.push_str("const TH=[");
        for (i, set) in theme_sets.iter().enumerate() {
            if i > 0 {
                js.push(',');
            }
            js.push_str(&js_string(&set.join(",")));
        }
        js.push_str("];\n");
        js.push_str("const THS=[];function th(i){return THS[i]||(THS[i]=new Set(TH[i].split(',')))}\n");
    }
    // Exact mode has no pattern tables, so the value validators the overlay
    // matcher needs are emitted here.
    if !pat_mode {
        js.push_str(&validators_js());
    }

    // XO: overlay records in the same flat P format (name, wildcard, family
    // id, conflict wid (unused, 0), ngroups, (nitems, spec codes...)...).
    js.push_str("const XO=[");
    for (i, r) in overlay_records.iter().enumerate() {
        if i > 0 {
            js.push(',');
        }
        for (j, e) in r.elems.iter().enumerate() {
            if j > 0 {
                js.push(',');
            }
            js.push_str(e);
        }
    }
    js.push_str("];\n");

    // XKW: overlay keyword strings (keyword codes index this array).
    js.push_str("const XKW=[");
    for (i, k) in xkw.iter().enumerate() {
        if i > 0 {
            js.push(',');
        }
        js.push_str(&js_string(k));
    }
    js.push_str("];\n");

    // XC: per-overlay-family conflict id lists, own family id first.
    js.push_str("const XC=[");
    for (i, conflicts) in xc.iter().enumerate() {
        if i > 0 {
            js.push(',');
        }
        js.push('[');
        for (j, id) in conflicts.iter().enumerate() {
            if j > 0 {
                js.push(',');
            }
            js.push_str(&id.to_string());
        }
        js.push(']');
    }
    js.push_str("];\n");

    // OW: sparse compiled family id -> overlay family ids (reverse edges:
    // a kept compiled class also drops the overlay families it edges).
    js.push_str("const OW={");
    for (i, (f, ids)) in ow.iter().enumerate() {
        if i > 0 {
            js.push(',');
        }
        js.push_str(&js_key(&f.to_string()));
        js.push_str(":[");
        for (j, id) in ids.iter().enumerate() {
            if j > 0 {
                js.push(',');
            }
            js.push_str(&id.to_string());
        }
        js.push(']');
    }
    js.push_str("};\n");

    js.push_str(OVERLAY_MATCH_JS);

    if opts.extend {
        js.push_str(&extend_api_js());
    }
    js
}

/// Spec code of one exact-mode overlay record item. Mirrors the pattern
/// table's `spec_code`: keywords and theme sets are deduplicated per overlay,
/// and `--spacing` maps to the `spacing` type code.
fn overlay_spec_code(
    spec: &GroupSpec,
    xkw: &mut Vec<String>,
    theme_sets: &mut Vec<Vec<String>>,
    theme_ids: &mut HashMap<String, usize>,
    ds: Option<&DesignSystem>,
) -> u16 {
    match spec {
        GroupSpec::Type(t) => type_code(t) as u16,
        GroupSpec::Keyword(k) => {
            let idx = match xkw.iter().position(|x| x == k) {
                Some(i) => i,
                None => {
                    xkw.push(k.clone());
                    xkw.len() - 1
                }
            };
            (KW_OFFSET + idx) as u16
        }
        GroupSpec::ThemeKey { prefix, has_star } => {
            if prefix == "--spacing" && !*has_star {
                return type_code("spacing") as u16;
            }
            let ds = ds.expect("exact-mode plugin overlay theme specs need the design system");
            let idx = match theme_ids.get(prefix) {
                Some(i) => *i,
                None => {
                    let mut values: Vec<String> = ds
                        .theme
                        .vars
                        .keys()
                        .filter(|k| k.starts_with(prefix))
                        .map(|k| k[prefix.len()..].to_string())
                        .collect();
                    values.sort();
                    values.dedup();
                    let i = theme_sets.len();
                    theme_sets.push(values);
                    theme_ids.insert(prefix.clone(), i);
                    i
                }
            };
            (TH_OFFSET + idx) as u16
        }
    }
}

