/// Value validators: exact behavioral port of `values.rs` plus the
/// `SpecItem::matches` type switch (`VT`, case numbers from `type_code`).
fn validators_js() -> String {
    let mut js = String::from(
        r#"const LU=/\d+(%|px|r?em|[sdl]?v([hwib]|min|max)|pt|pc|in|cm|mm|cap|ch|ex|r?lh|cq(w|h|i|b|min|max))|\b(calc|min|max|clamp)\(.+\)|^0$/;const CF=/^(rgba?|hsla?|hwb|(ok)?(lab|lch)|color-mix)\(.+\)$/;function N(v){return /^[+-]?(\d+(\.\d*)?|\.\d+)([eE][+-]?\d+)?$/.test(v)||v==='inf'||v==='+inf'||v==='-inf'||v==='infinity'||v==='+infinity'||v==='-infinity'||v==='NaN'||v==='nan'}function I(v){return /^[+-]?\d+$/.test(v)}function L(v){return LU.test(v)&&!CF.test(v)}function AV(v){return /^\[(?:(\w[\w-]*):)?(.+)\]$/.test(v)}function V(v){return /^\((?:(\w[\w-]*):)?(.+)\)$/.test(v)}function F(v){return /^\d+(\.\d+)?\/\d+(\.\d+)?$/.test(v)}function P1(v){const m=/^\[(?:(\w[\w-]*):)?(.+)\]$/.exec(v);return m?[m[1]||'',m[2]]:0}function P2(v){const m=/^\((?:(\w[\w-]*):)?(.+)\)$/.exec(v);return m?[m[1]||'',m[2]]:0}"#,
    );
    js.push_str("function VT(c,v){switch(c){");
    for (name, body) in VT_CASES {
        let code = type_code(name);
        if name.starts_with("a-") || name.starts_with("v-") {
            let parser = if name.starts_with("v-") { "P2" } else { "P1" };
            js.push_str(&format!(
                "case {code}:{{const p={parser}(v);if(!p)return 0;const l=p[0],x=p[1];return {body}}};"
            ));
        } else {
            js.push_str(&format!("case {code}:return {body};"));
        }
    }
    js.push_str("}return 0}");
    js
}

